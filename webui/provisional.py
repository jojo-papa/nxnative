"""Survey a game without a registered profile and write a provisional one.

The upstream NSP pipeline surveys an unknown title and writes a provisional
profile outside the repository (scripts/build_ipa_from_nsp.py). The WebUI has
to do the same before it starts a build because the target checks and the
Windows builder need a profile folder. The profile stays in the task folder;
nothing is added to dm/games.

The survey and profile format intentionally follow the upstream code. Keep
EMPTY_TABLES and write_profile in step with it when syncing upstream.
"""
import importlib
from pathlib import Path
import re
import shutil
import sys


EMPTY_TABLES = {
    'shader_map.tsv': '# kind: evidence  provisional profile: filled by the shader split (a Vulkan game\'s SPIR-V shaders go through the Vulkan layer and leave it empty)\npackage\tindex\tstage\tdm_ctl_sha16\tsource\n',
    'shader_facts.tsv': '# Answer table for translation queries (generated by dm/gfx/tools/shader_split.py, do not edit): key <TAB> fact JSON. Provisional profile: filled by the shader split\n',
    'shader_pairs.tsv': '# kind: evidence  vertex / pixel shader pairs within BNSH variations (generated by dm/gfx/tools/shader_split.py, do not edit): vertex key <TAB> pixel key\n',
    'shader_map.tsv.conflicts.tsv': '# kind: evidence  control-section key conflict rulings: empty\ndm_ctl_sha16\tchosen_pc\tclass\tcandidates\trecords\n',
    'bf_want.tsv': '# generated\n',
    'pso_manifest.tsv': '# Prewarm seed list (shipped in the app, next to shader_map.tsv). Rows: S<TAB>shader key<TAB>stage / R<TAB>render pipeline key (pso_skey hex) / C<TAB>compute shader key.\n'
                        '# Provisional profile: empty until recorded on the Mac (DM_PSO_MANIFEST=off DM_PSO_RECORD).\n',
}


def _module(directory, name):
    directory = str(Path(directory))
    if directory not in sys.path:
        sys.path.insert(0, directory)
    return importlib.import_module(name)


def profile_guess(repo):
    return _module(Path(repo) / 'dm/games', 'profile_guess')


def nacp(repo):
    return _module(Path(repo) / 'dm/tools', 'nacp')


def ipa_name(name, app):
    """The upstream IPA name: ASCII words joined, or the title ID."""
    words = re.findall(r'[A-Za-z0-9]+', name.replace("'", '').replace('’', ''))
    words = [w.capitalize() if w.isupper() and len(w) > 1 else w[:1].upper() + w[1:] for w in words]
    return (''.join(words)[:48] or f'{app:016X}') + '.ipa'


def survey(repo, extractor, keys, base, update, work, run, folder, version):
    """Extract the modules and a RomFS manifest, then read the survey facts.

    `version` is the profile version the build will use (v0 or the update's
    version). Nothing from the game's RomFS is written beyond the manifest.
    """
    work = Path(work)
    if work.exists():
        shutil.rmtree(work)
    run(folder, [extractor, keys, base, update or '-', work, '--manifest'])
    exefs, manifest = work / 'ExeFS', work / 'romfs_manifest.tsv'
    if not (exefs / 'main').is_file() or not manifest.is_file():
        raise ValueError('The title survey did not produce its code modules and RomFS manifest.')
    pg = profile_guess(repo)
    facts = pg.facts_of(exefs, manifest)
    if 'main' not in facts['mods']:
        raise ValueError('The title survey found no main module.')
    guessed = pg.guess(facts)
    modules = guessed['modules'][0].split()
    romfs = facts['romfs']
    sources = pg.shader_sources(
        facts['mods']['main']['imports'], facts['glsl_src'],
        [name for name in modules if 'glslcCompile' in facts['mods'][name]['exports']],
        romfs['mags']['SPIR-V'],
        romfs['exts'].get('.pak', 0) if facts.get('main_markers', set()) & {'Unreal', 'Unreal 4'} else 0,
        romfs['mags']['Trinity pack'], gl_names=facts.get('gl_names', 0))
    nc = nacp(repo)
    return dict(F=facts, guess=guessed, sources=sources,
                name=nc.name(work / 'control.nacp') or '', display=nc.version(work / 'control.nacp') or '?',
                version=version, survey=str(work))


def write_profile(profile_dir, app, facts, pg=None):
    """Write game.tsv and the empty tables; an existing profile is reused."""
    app = int(app, 16) if isinstance(app, str) else int(app)
    profile_dir = Path(profile_dir)
    profile_dir.mkdir(parents=True, exist_ok=True)
    if (profile_dir / 'game.tsv').exists():
        return False
    F, R = facts['F'], facts['F']['romfs']
    G = facts.get('guess')
    if G is None:
        pg = pg or profile_guess(Path(__file__).resolve().parents[1])
        G = pg.guess(F)
    groups, seen = [], {'main', 'other'}
    for name, _ in R['dirs'].most_common(24):
        group = re.sub(r'[^a-z0-9]', '', name.lower())[:16] or 'g'
        while group in seen:
            group += 'x'
        seen.add(group)
        groups.append(f'/{name}/={group}')
    store = sorted(extension for extension, amount in R['extb'].items()
                   if extension and R['exts'][extension] and
                   (amount / R['exts'][extension] >= 1 << 20 or 2 * R['extc'][extension] >= R['exts'][extension]))
    name = facts.get('name') or f'{app:016X}'
    modules = G['modules'][0].split()
    tab = '\t'

    def key(name, default=None):
        value, why = G[name] if name in G else (default, '')
        return [] if value is None else ([f'# {why}'] if why else []) + [f'{name}{tab}{value}']

    lines = [
        '# Provisional game profile (generated by the WebUI survey with dm/games/profile_guess.py, not checked by hand)',
        f'# {name}, SDK {F["sdk"] or "?"}, survey {facts.get("survey", "")}', '',
        '# ---- Identity ----', f'title_id{tab}{app:016X}', f'program_id{tab}{(F["program"] or app):016X}', '',
        '# ---- App ----', f'name{tab}{name}', f'ipa{tab}{ipa_name(name, app)}', f'app_category{tab}public.app-category.games',
        *key('pad_layout'), *key('op_mode'), '',
        '# ---- Versions ----',
        tab.join(['build', facts['version'], facts['display']] + [f'{module}={F["mods"][module]["bid"]}' for module in modules]),
        f'package{tab}{facts["version"]}', f'shader_versions{tab}{facts["version"]}', '',
        '# ---- Files ----', *key('modules'), f'romfs_marker{tab}{R["biggest"][1]}',
        f'zip_store{tab}{":".join(store + [".metallib"])}', '',
        '# ---- Memory ----', *key('mem_reserve'), *key('mem_alias'), *key('mem_stack'), *key('app_pool'), *key('sys_resource'), '',
        '# ---- Shader split ----', *key('shader_groups', ' '.join(groups) or '/=romfs'),
        f'shader_note{tab}{name} shaders (provisional profile)',
    ]
    (profile_dir / 'game.tsv').write_text('\n'.join(lines) + '\n', encoding='utf-8')
    for filename, text in EMPTY_TABLES.items():
        (profile_dir / filename).write_text(text)
    return True


def report(facts):
    """A JSON-safe summary for inspection.json and a task artifact."""
    F = facts['F']
    return {
        'name': facts.get('name', ''),
        'display_version': facts.get('display', '?'),
        'profile_version': facts.get('version', 'v0'),
        'graphics': facts['sources']['graphics'][0],
        'shader_sources': {name: bool(value[0]) for name, value in facts['sources'].items()},
        'modules': {name: {'kind': module['kind'], 'build_id': module['bid'],
                           'bss_bytes': module['bss'], 'far_patch_area': module['far']}
                    for name, module in F['mods'].items()},
        'sdk': F['sdk'],
        'system_resource_bytes': F['sysres'],
        'romfs_files': F['romfs']['n'],
        'romfs_bytes': F['romfs']['bytes'],
        'warning': 'Provisional profile: values were guessed from the survey; this app may not boot.',
    }
